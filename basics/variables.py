# 变量与数据类型
# 学习日期: 2024-XX-XX

# 变量定义
name = "Python"
age = 30
is_fun = True
price = 3.14

# 打印变量
print(f"语言: {name}")
print(f"年龄: {age}")
print(f"有趣吗: {is_fun}")
print(f"价格: {price}")

# 数据类型
print(type(name))      # <class 'str'>
print(type(age))       # <class 'int'>
print(type(is_fun))    # <class 'bool'>
print(type(price))     # <class 'float'>
